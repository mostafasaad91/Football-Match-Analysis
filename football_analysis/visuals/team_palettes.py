"""
team_palettes.py
═════════════════════════════════════════════════════════════════════════════
Real kit colours for clubs and national teams.

This module is pure data plus two small lookup helpers. It is the single
source of truth for "what colour is this team", and it is merged into
``football_match_analysis.TOP5_2025_26_TEAM_PALETTES`` at import time so all
existing call sites (``_team_palette``, ``get_team_color``,
``choose_matchup_colors``) pick the new teams up automatically.

Coverage
────────
Clubs
    • The big-5 leagues (Premier League, LaLiga, Serie A, Bundesliga, Ligue 1)
      — these already live in ``football_match_analysis`` and are not
      duplicated here.
    • Every UEFA domestic league that supplies Champions League, Europa League
      or Conference League entrants. Organising by league instead of by a
      single season's league-phase roster means the table stays correct when
      qualification changes from year to year.
    • Continental competitions outside UEFA: CAF Champions League /
      Confederation Cup, AFC Champions League Elite / Two, Copa Libertadores /
      Sudamericana, and the CONCACAF Champions Cup.

National teams
    • All UEFA, CONMEBOL, CONCACAF and OFC members, plus every CAF and AFC
      member that competes in the Africa Cup of Nations / Asian Cup.

Format
──────
``name -> [primary, secondary, tertiary]``

    primary    dominant home-shirt colour — this is the colour a visual uses.
    secondary  the shirt's accent / stripe colour.
    tertiary   a clash colour, used automatically when two teams on the same
               chart would otherwise render too close together.

Colours are chosen for the shirt identity, not the crest: a side that plays in
white with a navy trim is white-first, even if the badge is mostly navy. Teams
whose primary is white or black keep it — the renderer's contrast pass is what
lifts them off the background, so the data layer stays honest.
"""

