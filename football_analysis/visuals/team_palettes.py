# ═════════════════════════════════════════════════════════════════════════════
# Combined view + merge helper
# ═════════════════════════════════════════════════════════════════════════════
ALL_TEAM_PALETTES: dict[str, list[str]] = {}
for _table in (
    UEFA_CLUB_PALETTES,
    CONTINENTAL_CLUB_PALETTES,
    NATIONAL_TEAM_PALETTES,
):
    ALL_TEAM_PALETTES.update(_table)


def merge_into(
    palettes: dict[str, list[str]],
    aliases: dict[str, str] | None = None,
    *,
    overwrite: bool = False,
) -> tuple[int, int]:
    """Merge this module's tables into an existing palette/alias mapping.

    ``overwrite=False`` (the default) means an entry that the host module has
    already curated by hand wins over the bulk table here, so this file can
    grow without silently changing colours somebody deliberately picked.

    Returns ``(palettes_added, aliases_added)``.
    """
    added_palettes = 0
    for name, colours in ALL_TEAM_PALETTES.items():
        if overwrite or name not in palettes:
            palettes[name] = list(colours)
            added_palettes += 1

    added_aliases = 0
    if aliases is not None:
        known = {key.lower() for key in palettes}
        for alias, target in EXTRA_TEAM_ALIASES.items():
            # Skip aliases whose target is not resolvable — a dangling alias
            # silently sends a team to the unknown-colour fallback.
            if target.lower() not in known:
                continue
            if overwrite or alias not in aliases:
                aliases[alias] = target
                added_aliases += 1

    return added_palettes, added_aliases
